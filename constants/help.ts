export function helpSectionsFor(role?: string | null): HelpSection[] {
  return role === 'employer' ? EMPLOYER_SECTIONS : WORKER_SECTIONS;
}

/** Работает ли поддержка прямо сейчас (по Москве). */
export function supportIsOpen(now: Date = new Date()): boolean {
  const mskHour = (now.getUTCHours() + 3) % 24;
  return mskHour >= SUPPORT_FROM_HOUR && mskHour < SUPPORT_TO_HOUR;
}
