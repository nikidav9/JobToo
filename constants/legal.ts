export const LEGAL_KEYS: LegalDocKey[] = ['terms', 'privacy', 'consent'];

/** Редакции по документам — в таком виде они ложатся в запись о согласии. */
export function legalVersions(): Record<LegalDocKey, string> {
  return {
    terms: LEGAL_DOCS.terms.version,
    privacy: LEGAL_DOCS.privacy.version,
    consent: LEGAL_DOCS.consent.version,
  };
}

/**
 * Отпечаток набора — одна строка вида
 * `terms:2026-06-25|privacy:2026-06-25|consent:2026-06-25`.
 *
 * Галочка при регистрации одна на все три документа, поэтому и сравнивать
 * удобнее набор целиком: изменилась любая редакция — отпечаток другой.
 */
export const LEGAL_STAMP: string = LEGAL_KEYS
  .map(k => `${k}:${LEGAL_DOCS[k].version}`)
  .join('|');

/**
 * Нужно ли спрашивать согласие заново.
 *
 * Пустая запись значит «не спрашивали вовсе» — так у всех, кто
 * регистрировался до 25 июня 2026, когда экрана с документами ещё не было.
 */
export function needsReconsent(recorded: string | null | undefined): boolean {
  return !recorded || recorded !== LEGAL_STAMP;
}

/** «25 июня 2026» — для показа в интерфейсе. */
export function formatLegalDate(version: string): string {
  const MONTHS = ['января', 'февраля', 'марта', 'апреля', 'мая', 'июня',
                  'июля', 'августа', 'сентября', 'октября', 'ноября', 'декабря'];
  const [y, m, d] = version.split('-').map(Number);
  if (!y || !m || !d) return version;
  return `${d} ${MONTHS[m - 1]} ${y}`;
}
