/**
 * Микро-тесты по профессиям.
 *
 * Пять вопросов, минута времени, один результат: подтверждён навык или нет.
 * Смысл не в экзамене — экзаменом на подработку никого не заманишь, — а в
 * том, чтобы отличить человека, который на складе работал, от человека,
 * который просто отметил галочку «кладовщик» при регистрации. Сегодня это
 * ровно одно и то же поле, и работодатель различить их не может никак.
 *
 * ── Почему вопросы лежат в коде, а не в базе ─────────────────────────────
 *
 * Их некому редактировать: редактора вопросов в панели нет, и делать его
 * ради четырёх наборов по пять штук дороже, чем выложить приложение. Когда
 * наборов станет много и менять их начнут еженедельно — переедут в базу.
 * Результаты, разумеется, в базе с самого начала.
 *
 * ── Про сами вопросы ─────────────────────────────────────────────────────
 *
 * Это первый набор, написанный по общим правилам склада и кухни. Их стоит
 * показать тому, кто в этих профессиях работает: вопрос, который кажется
 * очевидным составителю и спорным практику, отсеет как раз практика.
 */

