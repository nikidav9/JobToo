/**
 * Загрузочный экран: только название.
 *
 * На фирменном оранжевом собирается «JobToo»: буквы приходят снизу по одной,
 * «Job» белым, «Too» чёрным. Когда слово собрано, по нему идёт тихая волна —
 * буквы по очереди чуть приподнимаются. Она и говорит, что приложение живо,
 * пока грузятся данные.
 *
 * ── Что здесь было раньше ─────────────────────────────────────────────────
 *
 * Сначала корзина с продуктами — наследство магазинной заготовки, к работе
 * отношения не имевшее. Потом коробка, прискакивавшая на место последней
 * буквы, как лампа у Pixar. Оба варианта решали одну задачу: чем-нибудь
 * занять экран. Но у загрузочного экрана задача другая — не развлечь, а не
 * раздражать на сотом запуске. Предмет, каждый раз проделывающий один и тот
 * же трюк, мозолит глаза первым.
 *
 * Поэтому здесь нет ничего, кроме названия. Контраст держится не картинкой, а
 * тем, что «Too» другого цвета: тот же приём, что в шапке приложения, и
 * человек узнаёт его сразу.
 *
 * ── Почему числа лежат здесь ──────────────────────────────────────────────
 *
 * Экранов два: нативный (components/SplashLoader.tsx) и статический в вебе
 * (app/+html.tsx), который показывается, пока грузится сам код приложения.
 * Раньше это были две рукописные копии одной анимации, и комментарий над ними
 * обещал, что они «совпадают один в один». Такое обещание живёт до первой
 * правки в одном из файлов.
 *
 * Теперь оба берут числа отсюда: нативный интерполирует, веб собирает
 * @keyframes. Разъехаться им больше негде.
 */

/** Полная длительность появления. Счётчик процентов считает от неё же. */
export const DRAW_MS = 1280;

/** Название по частям: светлая и тёмная. */
export const WORD_LIGHT = 'Job';
export const WORD_DARK = 'Too';
/** Все буквы подряд — по этому списку считаются задержки. */
export const WORD = WORD_LIGHT + WORD_DARK;

export const WHITE = '#FFFFFF';
/** Тот же чёрный, что в шапке приложения. */
export const INK = '#141414';
export const ORANGE = '#FF6B1A';

/** Буква приходит снизу и проявляется. */
export const LETTER_RISE_MS = 380;
export const LETTER_STAGGER_MS = 70;
/** Насколько буква поднимается к своему месту, в долях кегля. */
export const LETTER_RISE_EM = 0.42;

/**
 * Пауза перед «Too».
 *
 * Чёрная половина приходит с задержкой, а не сразу за белой: смена цвета —
 * единственное событие на этом экране, и если она случается в общем потоке
 * букв, её никто не замечает.
 */
export const DARK_DELAY_MS = 140;

/**
 * Волна по собранному слову.
 *
 * Начинается, когда буквы на месте, и повторяется, пока экран висит. Подъём
 * нарочно крошечный: заметное движение на загрузочном экране читается как
 * «что-то происходит», а незаметное — как «всё идёт, ждём». Нужно второе.
 */
export const WAVE_START_MS = 760;
export const WAVE_PERIOD_MS = 1900;
export const WAVE_STAGGER_MS = 85;
/** Подъём буквы в волне, в долях кегля. */
export const WAVE_LIFT_EM = 0.055;
/** До какой прозрачности буква приглушается между волнами. */
export const WAVE_DIM = 0.82;

/** Когда буква начинает выходить — с учётом паузы перед тёмной половиной. */
export function letterDelay(index: number): number {
  const пауза = index >= WORD_LIGHT.length ? DARK_DELAY_MS : 0;
  return index * LETTER_STAGGER_MS + пауза;
}

/** Цвет буквы по её месту в слове. */
export function letterColor(index: number): string {
  return index < WORD_LIGHT.length ? WHITE : INK;
}
