// Дашборд живёт на Vercel и больше нигде. Раньше здесь была вторая сборка —
// статическая, под GitHub Pages. Толку от неё не было: статика не выполняет
// серверный код, поэтому маршруты /api/* в неё не попадали — ни пересылка
// вебхука бота, ни веб-пуши, ни сброс пароля. Публикация к тому же ни разу не
// прошла: Pages для репозитория не включён.
// standalone — чтобы дашборд можно было увезти с Vercel на свой сервер.
//
// Обычная сборка требует, чтобы рядом лежали все зависимости: это сотни
// мегабайт, которые пришлось бы либо тащить на сервер, либо собирать там.
// Второе исключено — Next.js съедает под два гигабайта, а на машине их
// четыре на всё вместе с базой, и сборка уронила бы её.
//
// standalone собирает сервер вместе с тем немногим, что ему нужно, в один
// каталог. Его и увозим — так же, как веб-версию: архив в выпуске, сервер
// забирает сам.
//
// На Vercel это ничего не меняет: он собирает по-своему и на эту настройку
// не смотрит. То есть включить её можно заранее, ничего не ломая.
// Корень сборки указан явно. В репозитории два package-lock.json — свой у
// приложения и свой у панели, — и Next выбирал корнем верхний. Оттуда он
// собирал бы standalone, складывая туда зависимости мобильного приложения.
