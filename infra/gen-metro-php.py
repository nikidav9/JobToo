#!/usr/bin/env python3
"""Пересобрать php-proxy/metro.php из constants/metro.ts.

Список станций написан один раз — в constants/metro.ts, где им пользуется
приложение. Серверу он тоже нужен: чужие фиды присылают станцию строкой
(«м. Тёплый Стан», «Теплый стан», «Тёплый Стан (Калужско-Рижская)»), и без
приведения к нашему написанию фильтр по метро не находит их вовсе.

Держать два списка руками — значит однажды получить станцию, которая есть у
приложения и которой нет у сервера. Поэтому один авторский список и эта
пересборка.

Запускать после правки constants/metro.ts:
    python3 infra/gen-metro-php.py
"""
import json
import pathlib
import re
import sys

КОРЕНЬ = pathlib.Path(__file__).resolve().parent.parent
ИСТОЧНИК = КОРЕНЬ / 'constants' / 'metro.ts'
ЦЕЛЬ = КОРЕНЬ / 'php-proxy' / 'metro.php'

текст = ИСТОЧНИК.read_text(encoding='utf-8')

линии = []
for кусок in re.finditer(
        r"id:\s*'([^']+)',\s*color:\s*'[^']*',\s*name:\s*'([^']+)',\s*stations:\s*\[(.*?)\]",
        текст, re.S):
    ид, имя, станции = кусок.group(1), кусок.group(2), кусок.group(3)
    линии.append({
        'id': ид,
        'name': имя,
        'stations': re.findall(r"'([^']+)'", станции),
    })

if not линии:
    print('не нашёл ни одной ветки в constants/metro.ts', file=sys.stderr)
    sys.exit(1)

пары = []
for л in линии:
    for ст in л['stations']:
        пары.append((ст, л['id']))

всего = len(пары)
уникальных = len({с for с, _ in пары})

# У пересадочной станции берём первую ветку, на которой она встретилась:
# dict() из списка оставил бы последнюю, и «Бульвар Рокоссовского» уезжал на
# МЦК вместо красной. Цвет ветки — единственное, на что это влияет, но
# выглядело бы это как ошибка в данных.
по_станциям = {}
for с, лид in пары:
    по_станциям.setdefault(с, лид)

тело = ',\n'.join(
    "    %s => %s" % (json.dumps(с, ensure_ascii=False), json.dumps(лид, ensure_ascii=False))
    for с, лид in по_станциям.items()
)

ЦЕЛЬ.write_text(f'''<?php
// СОБРАНО АВТОМАТИЧЕСКИ — не править руками.
// Источник: constants/metro.ts. Пересборка: python3 infra/gen-metro-php.py
//
// Станций: {уникальных} (записей с пересадками: {всего}), веток: {len(линии)}.
//
// Зачем это на сервере. Чужие фиды присылают станцию как придётся:
// «м. Тёплый Стан», «Теплый стан», «Тёплый Стан (Калужско-Рижская)».
// Приложение фильтрует по точному совпадению с нашим написанием — значит
// приводить надо здесь, на входе, один раз, а не в каждом месте показа.

return [
{тело}
];
''', encoding='utf-8')

print(f'{ЦЕЛЬ.relative_to(КОРЕНЬ)}: станций {уникальных}, веток {len(линии)}')
