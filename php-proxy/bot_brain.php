/**
 * Открытые смены: ближе — выше, при равной дороге раньше по дате.
 *
 * Прятать дальние станции нельзя — иногда их всего одиннадцать на всю Москву,
 * и человек с Владыкина готов доехать до Марьиной Рощи. Но и выдавать их за
 * соседние тоже нельзя: расстояние пишем прямо в строке.
 */
function bot_shifts_near(?string $station, int $limit = 5): array {
    $today = gmdate('Y-m-d', time() + 3 * 3600);
    $rows = sb('GET', 'jm_vacancies', [
        'select' => 'id,title,company,metro_station,address,date,time_start,time_end,salary',
        'status' => 'eq.open',
        'date'   => 'gte.' . $today,
        'order'  => 'date.asc',
        'limit'  => '60',
    ]);
    if (empty($rows)) return [];
    foreach ($rows as $k => $v) {
        $rows[$k]['_stops'] = bot_stops_between($station, $v['metro_station'] ?? null);
    }
    usort($rows, function ($a, $b) {
        $sa = $a['_stops'] ?? 999; $sb = $b['_stops'] ?? 999;
        return $sa === $sb ? strcmp((string)$a['date'], (string)$b['date']) : $sa <=> $sb;
    });
    return array_slice($rows, 0, $limit);
}

/** Строка смены. Оплата — главное, поэтому она в строке всегда. */
function bot_shift_line(array $v): string {
    $when = bot_date_ru((string)($v['date'] ?? ''));
    $time = ($v['time_start'] ?? '') !== '' ? ' ' . $v['time_start'] . '–' . $v['time_end'] : '';
    $pay  = ((float)($v['salary'] ?? 0)) > 0
        ? number_format((float)$v['salary'], 0, ',', ' ') . ' ₽'
        : 'оплата сдельная, нормативы в карточке';
    $far  = '';
    if (isset($v['_stops'])) {
        if ($v['_stops'] === 0)                 $far = ' (это ваша станция)';
        elseif ($v['_stops'] <= BOT_NEAR_STOPS) $far = ' (' . $v['_stops'] . ' ост. от вас)';
    }
    return '• ' . ($v['title'] ?? 'Смена') . ' — м. ' . ($v['metro_station'] ?? '?') . $far
         . ', ' . $when . $time . ', ' . $pay;
}

function bot_shifts_text(?string $station, ?callable $filter = null, string $noneText = ''): string {
    $rows = bot_shifts_near($station, 40);
    if ($filter) $rows = array_values(array_filter($rows, $filter));
    $rows = array_slice($rows, 0, 5);
    if (empty($rows)) {
        return $noneText !== '' ? $noneText : 'Сейчас открытых смен нет. Как появятся — сообщу.';
    }
    $near = array_filter($rows, fn($v) => ($v['_stops'] ?? null) !== null && $v['_stops'] <= BOT_NEAR_STOPS);
    $head = $station === null
        ? 'Открытые смены сейчас:'
        : ($near
            ? "Смены рядом с вами (метро {$station}):"
            : "Рядом с метро {$station} смен сейчас нет. Вот всё, что открыто — ехать дальше:");
    return $head . "\n" . implode("\n", array_map('bot_shift_line', $rows))
         . "\n\nОткликнуться — в приложении, в два тапа.";
}

/** Постоянные вакансии — их спрашивают отдельно от смен. */
function bot_perm_text(?string $station): string {
    $rows = sb('GET', 'jm_perm_vacancies', [
        'select' => 'id,title,company,metro_station,salary,schedule',
        'status' => 'eq.open',
        'limit'  => '60',
    ]);
    if (empty($rows)) return 'Открытых постоянных вакансий сейчас нет. Как появятся — сообщу.';
    foreach ($rows as $k => $v) $rows[$k]['_stops'] = bot_stops_between($station, $v['metro_station'] ?? null);
    usort($rows, fn($a, $b) => ($a['_stops'] ?? 999) <=> ($b['_stops'] ?? 999));
    $lines = [];
    foreach (array_slice($rows, 0, 5) as $v) {
        $far = isset($v['_stops']) && $v['_stops'] !== null && $v['_stops'] <= BOT_NEAR_STOPS
            ? ($v['_stops'] === 0 ? ' (это ваша станция)' : ' (' . $v['_stops'] . ' ост. от вас)') : '';
        $pay = ((float)($v['salary'] ?? 0)) > 0
            ? number_format((float)$v['salary'], 0, ',', ' ') . ' ₽/мес' : 'оплата по договорённости';
        $lines[] = '• ' . ($v['title'] ?? 'Вакансия') . ' — м. ' . ($v['metro_station'] ?? '?') . $far
                 . ', ' . $pay . (($v['schedule'] ?? '') !== '' ? ', ' . $v['schedule'] : '');
    }
    return "Постоянная работа сейчас:\n" . implode("\n", $lines) . "\n\nОткликнуться — в приложении.";
}

