-- Когда пользователь последний раз пользовался приложением.
-- Нужно в двух местах: в шапке чата («в сети» / «был в сети 20 минут назад»)
-- и в дашборде, чтобы видеть, кто давно не заходил.
-- Приложение обновляет отметку при запуске, при возврате из фона и раз в
-- несколько минут, пока экран открыт.

alter table jm_users add column if not exists last_seen_at timestamptz;

-- Выборки в дашборде идут по этой колонке с сортировкой
create index if not exists jm_users_last_seen_idx on jm_users (last_seen_at desc nulls last);
