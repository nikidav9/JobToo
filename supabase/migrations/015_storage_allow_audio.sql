-- УЖЕ ПРИМЕНЕНО в рабочей базе — настройки бакета правились через Storage API.
-- Файл оставлен, чтобы изменение не потерялось, если базу будут поднимать
-- заново. Повторный запуск безопасен: список дополняется без повторов.
--
-- Голосовые сообщения не загружались никогда.
--
-- Бакет avatars заведён под картинки, и у него задан список разрешённых типов
-- файлов — только изображения. Любая попытка положить туда звук отвергалась
-- с ошибкой 415 «mime type audio/m4a is not supported». Проверено запросом:
-- image/jpeg проходит, audio/m4a, audio/mp4 и audio/webm — нет.
--
-- Приложение эту ошибку только писало в лог и отправляло сообщение дальше,
-- со ссылкой на файл, которого нет. Получатель видел обычное голосовое,
-- нажимал — и слышал тишину. Отправка теперь падает с ошибкой (см. правку
-- в app/chat-room.tsx), но загружать всё равно должно быть куда.
--
-- Добавляем звуковые типы к тем, что уже разрешены. Список именно дополняем,
-- а не заменяем: если стереть его целиком, вместе с ним уедут картинки.
--
-- m4a — то, что пишет приложение на телефоне (AAC внутри контейнера mp4).
-- webm — то, что пишет браузер, когда не умеет mp4.
-- Остальные на будущее: форматы у браузеров разнятся и меняются.

update storage.buckets
set allowed_mime_types = (
  select array_agg(distinct t)
  from unnest(
    coalesce(allowed_mime_types, array[]::text[]) || array[
      'audio/mp4',
      'audio/m4a',
      'audio/x-m4a',
      'audio/aac',
      'audio/mpeg',
      'audio/webm',
      'audio/ogg',
      'audio/wav'
    ]
  ) as t
)
where id = 'avatars'
  -- null означает «разрешено всё» — тогда трогать нечего.
  and allowed_mime_types is not null;

