--
-- Бот умеет распознать такую просьбу и вежливо ответить, но до сих пор ему
-- нечем было её запомнить: через два дня рассылка написала бы снова. Одна
-- колонка честнее любого вежливого ответа.
--
-- Касается только напоминаний. Ответы директоров, сообщения в чате и всё,
-- что человек ждёт сам, приходят по-прежнему: отписка от рекламы не должна
-- отписывать от работы.

alter table jm_users
  add column if not exists nudge_off boolean not null default false;
