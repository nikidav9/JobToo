-- Ссылки на файлы — с временного имени на домен.
--
-- Когда файлы переехали из облака, своего имени у сервера ещё не было, и
-- ссылки переписали на 147.45.184.99.sslip.io — адрес, собранный из IP
-- сторонним сервисом. Это годилось как времянка и держалось на двух чужих
-- вещах сразу: что sslip.io продолжит работать и что адрес сервера не
-- поменяется. Первое от нас не зависит вовсе, второе — ровно до первого
-- переезда машины.
--
-- Домен теперь наш и указывает сюда, значит ссылки должны вести на него.
--
-- Меняем только начало адреса, имена файлов сохраняются. Старые ссылки
-- продолжат работать, пока жив сертификат на временное имя, — но их
-- больше не останется ни в базе, ни в новых загрузках.

update jm_users
   set avatar_url = replace(avatar_url, 'https://147.45.184.99.sslip.io', 'https://jobtoo.ru')
 where avatar_url like '%147.45.184.99.sslip.io%';

-- В сообщениях адрес лежит прямо в тексте, с пометкой [img] или [voice].
