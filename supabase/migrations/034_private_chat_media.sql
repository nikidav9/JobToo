-- Медиа переписки — в отдельный, закрытый бакет.
--
-- Фотографии и голосовые из чатов складывались в бакет `avatars`, а он
-- заведён публичным (см. infra/migrate.sh). Ссылка вида
--     …/storage/v1/object/public/avatars/chat/{id чата}_{время}.jpg
-- открывается кем угодно, без авторизации и навсегда: достаточно один раз
-- куда-нибудь попасть — в пересланное сообщение, в журнал промежуточного
-- сервера, в чужую историю браузера, — и файл доступен всем и всегда.
--
-- Аватар в публичном бакете — решение спорное, но осмысленное: его и так
-- показывают другим людям. Переписка — нет.
--
-- ── Что здесь и чего здесь нет ────────────────────────────────────────────
--
-- Здесь: закрытый бакет `chat-media`. Файл из него отдаётся только по
-- подписанной ссылке с коротким сроком жизни, которую выдаёт php-proxy.
-- Утёкшая ссылка перестаёт работать сама.
--
-- Чего здесь нет: проверки, что файл просит именно участник переписки.
-- Сделать её сейчас нечем — у прокси нет способа узнать, кто его зовёт:
-- приложение предъявляет один общий секрет, зашитый в сборку, а не токен
-- конкретного человека. Значит тот, у кого этот секрет есть и кто знает
-- путь к файлу, подпись получит.
--
-- Это по-прежнему заметно лучше публичного бакета: ссылки перестают быть
-- вечными и перестают работать в отрыве от приложения. Но честная защита
-- переписки требует сессионных токенов, а это отдельная работа, и делать
-- вид, что она сделана, нельзя.

insert into storage.buckets (id, name, public)
values ('chat-media', 'chat-media', false)
on conflict (id) do update set public = false;

-- Политик не создаём: без них к бакету не подойти никому, кроме служебной
-- роли, которая RLS обходит. Под ней ходит php-proxy — он и подписывает.
alter table storage.objects enable row level security;

notify pgrst, 'reload schema';
