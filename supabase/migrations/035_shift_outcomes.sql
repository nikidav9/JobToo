-- Чем закончилась смена — по-настоящему, а не «да/нет».
--
-- До этого у отклика было два исхода: `shift_completed` (директор нажал
-- «Подтвердить») и `cancelled` (нажал «Отменить»). Второе означало сразу
-- три разные вещи: работник не вышел; работник заранее отказался; смену
-- отменил сам работодатель. Для человека, который на неё смотрит, разница
-- решающая — в первом случае виноват работник, в третьем работодатель, —
-- а в базе всё это была одна и та же галочка.
--
-- Опоздания не фиксировались вообще никак.
--
-- Без этих двух цифр — процент выходов и процент опозданий — рейтинг
-- работника считать не из чего: остаётся только средняя оценка звёздами,
-- то есть впечатление, а не факт. И, в отличие от всего остального в
-- проекте, эти данные нельзя добрать задним числом: они копятся только с
-- того дня, когда их начали спрашивать.
--
-- Старые колонки остаются и продолжают заполняться: по ним написан весь
-- существующий экран «Мэтчи», и переписывать его целиком ради одного поля
-- незачем. `outcome` — источник правды, `shift_completed`/`cancelled` —
-- его проекция.

alter table jm_likes
    -- worked            — вышел и отработал
    -- no_show           — не вышел и не предупредил
    -- worker_cancelled  — отказался заранее, предупредив
    -- employer_cancelled— смену отменил работодатель
    -- cancelled_legacy  — отменено до появления причин; кто виноват, неизвестно
    add column if not exists outcome      text,
    -- Сколько минут опоздания. 0 — пришёл вовремя, null — не спрашивали.
    -- Именно ноль, а не null: «пришёл вовремя» это ответ, а не отсутствие
    -- ответа, и в проценте пунктуальности он должен считаться.
    add column if not exists late_minutes integer,
    add column if not exists outcome_at   timestamptz,
    -- Кто отметил исход. Сегодня всегда работодатель, но спор по невыходу
    -- разбирать придётся, и знать, с чьих слов запись, нужно уже сейчас.
    add column if not exists outcome_by   text;

-- Разбираем то, что уже накопилось.
--
-- Завершённые переносим как есть: «подтвердил» однозначно значит «вышел».
-- А отменённым ставим `cancelled_legacy`, а не `no_show`: причину у нас
-- никто не спрашивал, и записать работнику невыход по догадке — это
-- испортить ему рейтинг за то, чего мы не знаем.
update jm_likes set outcome = 'worked'
 where outcome is null and shift_completed = true;

update jm_likes set outcome = 'cancelled_legacy'
 where outcome is null and cancelled = true;

-- Сторож от опечатки в коде: неизвестное слово в `outcome` не запишется
-- молча, а свалит запрос. Иначе один неверный литерал тихо выпадает из
-- статистики, и заметить это можно только по расхождению цифр.
do $$ begin
    alter table jm_likes
        add constraint jm_likes_outcome_chk check (
            outcome is null or outcome in (
                'worked', 'no_show', 'worker_cancelled',
                'employer_cancelled', 'cancelled_legacy'
            )
        );
exception when duplicate_object then null;
end $$;

-- Считать статистику работника: «все исходы такого-то». Без индекса это
-- перебор всей таблицы откликов на каждый пересчёт рейтинга.
create index if not exists jm_likes_worker_outcome_idx
    on jm_likes (worker_id, outcome) where outcome is not null;
