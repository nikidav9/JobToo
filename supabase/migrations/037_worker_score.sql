-- JobToo Score: рейтинг работника из фактов, а не из впечатления.
--
-- До этого о человеке было известно одно число — средняя оценка звёздами.
-- Она говорит, понравился ли он, и ничего не говорит о том, выходил ли он на
-- смены и приходил ли вовремя. Работодателю, который набирает двадцать
-- человек на завтра, нужно как раз второе.
--
-- Считаем из того, что действительно записано, и ни из чего больше. Осей в
-- презентации восемь; здесь их шесть, потому что «качество» и «скорость»
-- появились только что (см. ниже), а «опыт на объектах» — это то же число
-- смен с другой стороны, и удваивать его вес нечестно.
--
-- Где число хранится. В самой строке пользователя, а не отдельной таблицей:
-- рейтинг нужен везде, где показывают человека — в списке кандидатов, в
-- карточке отклика, в подборе, — и лишний запрос в каждом из этих мест
-- обошёлся бы дороже, чем шесть колонок.

-- ─── Оценка после смены: не только звёзды ────────────────────────────────────
--
-- Работодатель ставил одну общую оценку, и в ней слипались «хорошо работал»
-- и «приятный человек». Две отдельные шкалы, обе необязательные: кто не
-- захочет отвечать, поставит только звёзды, как раньше.
alter table jm_ratings
    add column if not exists quality numeric,   -- качество работы, 1–5
    add column if not exists speed   numeric;   -- скорость работы, 1–5

-- ─── Посчитанный рейтинг ─────────────────────────────────────────────────────
alter table jm_users
    -- 0–100. null — данных ещё слишком мало, и число было бы выдумкой.
    -- Это важнее, чем кажется: у новичка с одной смены «100 из 100» врёт
    -- ровно так же, как «0 из 100», и оба числа решают за работодателя.
    add column if not exists score             integer,
    -- Сколько смен отработано — знаменатель всего остального.
    add column if not exists score_shifts      integer not null default 0,
    -- Доли 0–1, чтобы показывать оси по отдельности, а не только итог.
    add column if not exists score_reliability numeric,  -- вышел / (вышел + не вышел)
    add column if not exists score_punctuality numeric,  -- вовремя / отмеченных
    add column if not exists score_quality     numeric,  -- средняя оценка качества / 5
    add column if not exists score_speed       numeric,  -- средняя оценка скорости / 5
    -- Сколько разных работодателей — «опыт на объектах» из презентации.
    add column if not exists score_employers   integer not null default 0,
    add column if not exists score_updated_at  timestamptz;

create index if not exists jm_users_score_idx on jm_users (score desc nulls last)
    where role = 'worker';
