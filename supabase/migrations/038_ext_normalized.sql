-- Приведённые поля у чужих вакансий.
--
-- Сборщик клал то, что прислали, слово в слово. Для показа этого хватало, для
-- поиска — нет, и это выяснилось ровно в тот день, когда чужие вакансии
-- впервые появились в приложении.
--
-- Станция. В фидах она приходит как придётся: «м. Тёплый Стан», «Теплый
-- стан», «Тёплый Стан (Калужско-Рижская)». Приложение сравнивает станцию с
-- нашим списком точным равенством — значит ни один из трёх вариантов не
-- совпадает ни с чем, и фильтр по метро для чужих вакансий не работает
-- вовсе. Причём молча: ничего не найдено, и непонятно, то ли вакансий нет,
-- то ли фильтр сломан.
--
-- Профессия. У наших вакансий она есть (work_type), у чужих был только
-- заголовок. Фильтровать по профессии сразу по обоим спискам было нечем.
--
-- Исходное написание не выбрасываем: если разбор ошибётся, по нему видно,
-- что именно прислал источник, а не только то, во что мы это превратили.

alter table jm_ext_vacancies
    -- Станция из нашего справочника, либо null, если разобрать не вышло.
    add column if not exists metro_station_norm text,
    add column if not exists metro_line_id      text,
    -- stocker | cook | shift_supervisor | picker | null.
    -- null — заголовок не похож ни на одну из наших профессий; такие
    -- вакансии остаются в поиске, просто не попадают под фильтр по
    -- профессии. Это честнее, чем свалить их в «кладовщика».
    add column if not exists work_type          text;

create index if not exists jm_ext_vac_metro_norm_idx
    on jm_ext_vacancies (metro_station_norm) where active;
create index if not exists jm_ext_vac_worktype_idx
    on jm_ext_vacancies (work_type) where active;
