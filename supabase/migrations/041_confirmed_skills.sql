-- Подтверждённые навыки — рядом с человеком, а не отдельным запросом.
--
-- Результаты тестов лежат в jm_skill_results, и это правильное для них
-- место: там попытки, даты, история. Но подбор кандидатов должен уметь
-- ответить «у кого из этих сорока подтверждён склад» без сорока запросов
-- или отдельного объединения на каждый список.
--
-- Поэтому короткий список подтверждённого дублируется в строку
-- пользователя — как и score. Источник правды остаётся один
-- (jm_skill_results), сюда его переписывает сервер при каждом заходе теста.

alter table jm_users
    add column if not exists confirmed_skills text[] not null default '{}';

-- Уже подтверждённое (если такое есть) переносим сразу: иначе до первой
-- пересдачи подбор считал бы, что не подтвердил никто.
update jm_users u
   set confirmed_skills = coalesce((
        select array_agg(r.work_type order by r.work_type)
          from jm_skill_results r
         where r.user_id = u.id and r.passed
   ), '{}')
 where u.role = 'worker';
